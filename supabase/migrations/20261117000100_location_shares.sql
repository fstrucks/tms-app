-- 1. Role helpers (security definer so policies don't recurse through company_members RLS).
create or replace function public.location_role(p_company uuid)
returns text language sql stable security definer set search_path = public as $$
  select case
    when auth.uid() is null or p_company is null then null
    when exists (select 1 from public.company_profiles p where p.id = p_company and p.owner_id = auth.uid()) then 'owner'
    else (select m.role from public.company_members m
           where m.profile_id = p_company and m.user_id = auth.uid() limit 1)
  end;
$$;

create or replace function public.location_is_office(p_company uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(public.location_role(p_company) in ('owner', 'management', 'dispatcher'), false);
$$;

create or replace function public.location_share_is_live(p_expires timestamptz, p_stopped timestamptz)
returns boolean language sql stable as $$
  select p_stopped is null and (p_expires is null or p_expires > now());
$$;

revoke execute on function public.location_role(uuid), public.location_is_office(uuid) from public, anon;
grant execute on function public.location_role(uuid), public.location_is_office(uuid) to authenticated;
revoke execute on function public.location_share_is_live(timestamptz, timestamptz) from public, anon;
grant execute on function public.location_share_is_live(timestamptz, timestamptz) to authenticated;

-- 2. Shares.
create table if not exists public.location_shares (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.company_profiles(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  truck_id uuid null references public.trucks(id) on delete set null,
  load_id uuid null references public.loads(id) on delete set null,
  started_at timestamptz not null default now(),
  expires_at timestamptz null,
  stopped_at timestamptz null,
  stopped_reason text null,
  stopped_by uuid null references auth.users(id) on delete set null,
  mode text not null,
  duration_hours integer null,
  auto_stop_on_delivered boolean not null default false,
  last_reminded_at timestamptz null,
  created_at timestamptz not null default now(),
  constraint location_shares_mode_check check (mode in ('timed', 'until_off')),
  constraint location_shares_duration_check check (
    (mode = 'timed' and duration_hours in (1, 4, 8, 24) and expires_at is not null)
    or (mode = 'until_off' and duration_hours is null and expires_at is null)
  ),
  constraint location_shares_reason_check check (
    stopped_reason is null or stopped_reason in ('user', 'office', 'expired', 'delivered', 'deleted')
  ),
  constraint location_shares_times_check check (expires_at is null or expires_at > started_at),
  constraint location_shares_stopped_check check (stopped_at is null or stopped_at >= started_at)
);

create unique index if not exists location_shares_one_active_per_user
  on public.location_shares (user_id) where stopped_at is null;
create index if not exists location_shares_company_live_idx
  on public.location_shares (company_id) where stopped_at is null;
create index if not exists location_shares_expire_idx
  on public.location_shares (expires_at) where stopped_at is null and expires_at is not null;
create index if not exists location_shares_load_idx
  on public.location_shares (load_id) where load_id is not null and stopped_at is null;

-- 3. Pings (historical points). No addresses, IPs, or names. company_id is denormalized for export and purge.
create table if not exists public.location_pings (
  id bigint generated by default as identity primary key,
  share_id uuid not null references public.location_shares(id) on delete cascade,
  company_id uuid not null references public.company_profiles(id) on delete cascade,
  lat double precision not null,
  lng double precision not null,
  accuracy_m double precision null,
  speed_mps double precision null,
  heading double precision null,
  recorded_at timestamptz not null,
  received_at timestamptz not null default now(),
  constraint location_pings_lat_check check (lat between -90 and 90),
  constraint location_pings_lng_check check (lng between -180 and 180),
  constraint location_pings_accuracy_check check (accuracy_m is null or accuracy_m >= 0),
  constraint location_pings_speed_check check (speed_mps is null or speed_mps >= 0),
  constraint location_pings_heading_check check (heading is null or (heading >= 0 and heading < 360))
);
create index if not exists location_pings_share_recorded_idx
  on public.location_pings (share_id, recorded_at desc);
create index if not exists location_pings_company_recorded_idx
  on public.location_pings (company_id, recorded_at);
create index if not exists location_pings_recorded_idx
  on public.location_pings (recorded_at);

-- 3b. BEFORE INSERT on pings: always copy company_id from the share so a client cannot spoof it.
-- (The insert policy compares s.company_id = location_pings.company_id; an unqualified "company_id"
-- inside the EXISTS subquery would bind to s.company_id and be always true.)
create or replace function public.location_pings_fill_from_share()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  s public.location_shares;
begin
  select * into s from public.location_shares where id = new.share_id;
  if not found then
    raise exception 'location_ping_no_share' using errcode = 'P0001';
  end if;
  new.company_id := s.company_id;
  return new;
end;
$$;

drop trigger if exists location_pings_fill_from_share on public.location_pings;
create trigger location_pings_fill_from_share
  before insert on public.location_pings
  for each row execute function public.location_pings_fill_from_share();

-- 4. Latest point per share (maintained by trigger; the API also upserts so tests and a missed trigger still work).
create table if not exists public.location_share_latest (
  share_id uuid primary key references public.location_shares(id) on delete cascade,
  company_id uuid not null references public.company_profiles(id) on delete cascade,
  user_id uuid not null,
  lat double precision not null,
  lng double precision not null,
  accuracy_m double precision null,
  speed_mps double precision null,
  heading double precision null,
  recorded_at timestamptz not null,
  updated_at timestamptz not null default now()
);
create index if not exists location_share_latest_company_idx
  on public.location_share_latest (company_id);

create or replace function public.location_pings_touch_latest()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  s public.location_shares;
begin
  select * into s from public.location_shares where id = new.share_id;
  if not found then return new; end if;
  insert into public.location_share_latest
    (share_id, company_id, user_id, lat, lng, accuracy_m, speed_mps, heading, recorded_at, updated_at)
  values
    (new.share_id, s.company_id, s.user_id, new.lat, new.lng, new.accuracy_m, new.speed_mps, new.heading, new.recorded_at, now())
  on conflict (share_id) do update set
    lat = excluded.lat,
    lng = excluded.lng,
    accuracy_m = excluded.accuracy_m,
    speed_mps = excluded.speed_mps,
    heading = excluded.heading,
    recorded_at = excluded.recorded_at,
    updated_at = now()
  where public.location_share_latest.recorded_at <= excluded.recorded_at;
  return new;
end;
$$;

drop trigger if exists location_pings_touch_latest on public.location_pings;
create trigger location_pings_touch_latest
  after insert on public.location_pings
  for each row execute function public.location_pings_touch_latest();

-- 5. Expiry + retention. Cutoffs are arguments (defaults match the plan) so they stay easy to change.
create or replace function public.expire_location_shares()
returns integer language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  update public.location_shares
     set stopped_at = now(), stopped_reason = 'expired'
   where stopped_at is null and expires_at is not null and expires_at <= now();
  get diagnostics n = row_count;
  return n;
end;
$$;

create or replace function public.purge_location_pings(
  p_max_age interval default interval '30 days',
  p_after_end interval default interval '7 days'
)
returns integer language plpgsql security definer set search_path = public as $$
declare n integer := 0; k integer;
begin
  delete from public.location_pings
   where recorded_at < now() - p_max_age;
  get diagnostics k = row_count; n := n + k;
  delete from public.location_pings p
   using public.location_shares s
   where p.share_id = s.id
     and s.stopped_at is not null
     and s.stopped_at < now() - p_after_end;
  get diagnostics k = row_count; n := n + k;
  delete from public.location_share_latest l
   using public.location_shares s
   where l.share_id = s.id
     and s.stopped_at is not null
     and s.stopped_at < now() - p_after_end;
  return n;
end;
$$;

revoke execute on function public.expire_location_shares() from public, anon, authenticated;
revoke execute on function public.purge_location_pings(interval, interval) from public, anon, authenticated;

-- 5b. Share write guards.
-- INSERT: always force stopped_at, last_reminded_at, stopped_by, stopped_reason to null (even for service_role).
-- UPDATE: service_role is exempt (cron expiry, expire-on-read, and auto-stop on delivery all use the service
--         client from the API). Authenticated callers cannot change locked columns, cannot un-stop, and may
--         only make the narrow stop / reminder updates below.

create or replace function public.location_is_service_role()
returns boolean language sql stable as $$
  select coalesce(nullif(auth.role(), ''), current_setting('request.jwt.claim.role', true), current_user) = 'service_role';
$$;
revoke execute on function public.location_is_service_role() from public, anon;
grant execute on function public.location_is_service_role() to authenticated, service_role;

create or replace function public.location_shares_force_insert_nulls()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.stopped_at := null;
  new.last_reminded_at := null;
  new.stopped_by := null;
  new.stopped_reason := null;
  return new;
end;
$$;

drop trigger if exists location_shares_force_insert_nulls on public.location_shares;
create trigger location_shares_force_insert_nulls
  before insert on public.location_shares
  for each row execute function public.location_shares_force_insert_nulls();

create or replace function public.location_shares_guard_update()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  is_sharer boolean := (auth.uid() is not null and auth.uid() = old.user_id);
  is_office boolean := public.location_is_office(old.company_id);
  stop_only boolean;
begin
  if public.location_is_service_role() then
    return new;
  end if;

  if new.company_id is distinct from old.company_id
     or new.user_id is distinct from old.user_id
     or new.started_at is distinct from old.started_at
     or new.mode is distinct from old.mode
     or new.duration_hours is distinct from old.duration_hours
     or new.expires_at is distinct from old.expires_at
     or new.id is distinct from old.id
     or new.created_at is distinct from old.created_at then
    raise exception 'location_share_locked' using errcode = 'P0001';
  end if;

  if old.stopped_at is not null then
    raise exception 'location_share_already_stopped' using errcode = 'P0001';
  end if;

  -- Reminder only (sharer): last_reminded_at may change; everything else must stay the same.
  if new.stopped_at is null and new.stopped_reason is not distinct from old.stopped_reason
     and new.stopped_by is not distinct from old.stopped_by then
    if new.truck_id is distinct from old.truck_id
       or new.load_id is distinct from old.load_id
       or new.auto_stop_on_delivered is distinct from old.auto_stop_on_delivered then
      raise exception 'location_share_not_allowed' using errcode = 'P0001';
    end if;
    if new.last_reminded_at is distinct from old.last_reminded_at then
      if not is_sharer then
        raise exception 'location_share_not_allowed' using errcode = 'P0001';
      end if;
      return new;
    end if;
    return new;
  end if;

  -- Stop only: stopped_at / stopped_reason / stopped_by. last_reminded_at and other fields must not change.
  if new.last_reminded_at is distinct from old.last_reminded_at
     or new.truck_id is distinct from old.truck_id
     or new.load_id is distinct from old.load_id
     or new.auto_stop_on_delivered is distinct from old.auto_stop_on_delivered then
    raise exception 'location_share_not_allowed' using errcode = 'P0001';
  end if;

  if new.stopped_at is null then
    raise exception 'location_share_not_allowed' using errcode = 'P0001';
  end if;
  if new.stopped_at < now() - interval '60 seconds' or new.stopped_at > now() + interval '60 seconds' then
    raise exception 'location_share_stop_time' using errcode = 'P0001';
  end if;

  if is_sharer then
    if new.stopped_reason not in ('user', 'delivered') then
      raise exception 'location_share_stop_reason' using errcode = 'P0001';
    end if;
    if new.stopped_by is not null and new.stopped_by is distinct from auth.uid() then
      raise exception 'location_share_stop_by' using errcode = 'P0001';
    end if;
    return new;
  end if;

  if is_office then
    if new.stopped_reason = 'office' then
      if new.stopped_by is distinct from auth.uid() then
        raise exception 'location_share_stop_by' using errcode = 'P0001';
      end if;
      return new;
    end if;
    -- Office (or a dispatcher marking the load delivered through a user token) may end a share
    -- tied to that load when auto_stop_on_delivered is on. The production path uses service_role
    -- (exempt above) from POST /api/loads/:id/stops/:stopId.
    if new.stopped_reason = 'delivered' and old.auto_stop_on_delivered and old.load_id is not null then
      if new.stopped_by is not null and new.stopped_by is distinct from auth.uid() then
        raise exception 'location_share_stop_by' using errcode = 'P0001';
      end if;
      return new;
    end if;
    raise exception 'location_share_stop_reason' using errcode = 'P0001';
  end if;

  raise exception 'location_share_not_allowed' using errcode = 'P0001';
end;
$$;

drop trigger if exists location_shares_guard_update on public.location_shares;
create trigger location_shares_guard_update
  before update on public.location_shares
  for each row execute function public.location_shares_guard_update();

-- 6. RLS
alter table public.location_shares enable row level security;
alter table public.location_pings enable row level security;
alter table public.location_share_latest enable row level security;

drop policy if exists location_shares_select on public.location_shares;
create policy location_shares_select on public.location_shares
  for select to authenticated
  using (user_id = auth.uid() or public.location_is_office(company_id));

drop policy if exists location_shares_insert on public.location_shares;
create policy location_shares_insert on public.location_shares
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and public.location_role(company_id) is not null
    and (load_id is null or exists (
      select 1 from public.loads ld
       join public.company_profiles p on p.owner_id = ld.user_id
       where ld.id = load_id and p.id = company_id
         and (ld.assigned_driver_user_id = auth.uid() or ld.user_id = auth.uid())
    ))
  );

-- Sharer can stop their own share and update reminder time; office can stop (stopped_reason = 'office').
-- Nobody can insert a share for another user (see insert policy). Office cannot start a share on someone's phone.
drop policy if exists location_shares_update on public.location_shares;
create policy location_shares_update on public.location_shares
  for update to authenticated
  using (user_id = auth.uid() or public.location_is_office(company_id))
  with check (user_id = auth.uid() or public.location_is_office(company_id));

drop policy if exists location_pings_select on public.location_pings;
create policy location_pings_select on public.location_pings
  for select to authenticated
  using (exists (
    select 1 from public.location_shares s
     where s.id = share_id and (s.user_id = auth.uid() or public.location_is_office(s.company_id))
  ));

drop policy if exists location_pings_insert on public.location_pings;
create policy location_pings_insert on public.location_pings
  for insert to authenticated
  with check (exists (
    select 1 from public.location_shares s
     where s.id = location_pings.share_id
       and s.user_id = auth.uid()
       and s.company_id = location_pings.company_id
       and public.location_share_is_live(s.expires_at, s.stopped_at)
  ));

drop policy if exists location_share_latest_select on public.location_share_latest;
create policy location_share_latest_select on public.location_share_latest
  for select to authenticated
  using (user_id = auth.uid() or public.location_is_office(company_id));
-- Inserts/updates go through the trigger (security definer) or the server (service role). No direct client writes.

grant select, insert, update on public.location_shares to authenticated;
grant select, insert on public.location_pings to authenticated;
grant usage, select on sequence public.location_pings_id_seq to authenticated;
grant select on public.location_share_latest to authenticated;

do $$ begin
