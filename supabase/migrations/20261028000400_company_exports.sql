-- Company export before delete (PR E1): job + link-event tables and a private bucket. Schema only, no data.
--
-- How it is used (E2/E3, not in this migration):
--   The company owner (only) starts a full export, or confirming company deletion starts one automatically.
--   A server job (service role) writes ZIP parts to the private `company-exports` bucket under exports/<job_id>/.
--   The owner gets an emailed link /export/<token>. Only sha256(token) is stored here. Opening the link
--   does not sign in, so it does not cancel a scheduled deletion.
--   Links and objects live until 7 days after the company purge (or 7 days after ready if no deletion),
--   then the daily cron deletes the objects and sets cleaned_at. Rows stay as an audit record.
--
-- Access: service role only. RLS is on with NO policies, and anon/authenticated get no grants.
-- company_profile_id / owner_id are NOT foreign keys on purpose: the purge deletes the company and the
-- owner's auth user, and these audit rows must outlive both (the 7-day window after purge).
-- Safe to re-run.

create table if not exists public.export_jobs (
  id uuid primary key default gen_random_uuid(),
  company_profile_id uuid not null,              -- company_profiles.id at request time (no FK, see above)
  owner_id uuid not null,                         -- company_profiles.owner_id at request time (no FK)
  requested_by uuid not null,                     -- auth user who asked; equals owner_id (owner-only), kept for audit
  trigger text not null default 'manual',
  status text not null default 'queued',
  deliver_to text null,                           -- owner email the link was sent to; nulled at cleanup
  member_ids uuid[] not null default '{}',        -- owner + members whose rows/files belong to the export, fixed at start
  cursor jsonb not null default '{}'::jsonb,      -- resume point for the step runner (phase, table, last id, part no)
  parts jsonb not null default '[]'::jsonb,       -- [{ n, object, bytes, sha256 }]
  file_count integer not null default 0,
  byte_count bigint not null default 0,
  missing_count integer not null default 0,
  error text null,                                -- short, user-safe message; never secrets
  token_hash text null,                           -- hex sha256 of the link token; the token itself is never stored
  deletion_request_id uuid null,                  -- account_deletion_requests.id when trigger = 'deletion' (#161; no FK)
  purge_at timestamptz null,                      -- when the company was (or will be) purged; null if no deletion
  expires_at timestamptz null,                    -- link + objects end; purge_at + 7 days, or ready + 7 days
  created_at timestamptz not null default now(),
  started_at timestamptz null,
  completed_at timestamptz null,
  cleaned_at timestamptz null,                    -- objects deleted, token_hash and deliver_to cleared
  constraint export_jobs_trigger_check check (trigger in ('manual', 'deletion')),
  constraint export_jobs_status_check check (status in ('queued', 'running', 'ready', 'failed', 'expired')),
  constraint export_jobs_owner_only check (requested_by = owner_id),
  constraint export_jobs_token_hash_shape check (token_hash is null or token_hash ~ '^[0-9a-f]{64}$'),
  constraint export_jobs_counts_check check (file_count >= 0 and byte_count >= 0 and missing_count >= 0)
);

create unique index if not exists export_jobs_token_hash_key on public.export_jobs (token_hash) where token_hash is not null;
create unique index if not exists export_jobs_one_open_per_company on public.export_jobs (company_profile_id) where status in ('queued', 'running');
create index if not exists export_jobs_company_created_idx on public.export_jobs (company_profile_id, created_at desc);
create index if not exists export_jobs_cleanup_idx on public.export_jobs (expires_at) where cleaned_at is null;

create table if not exists public.export_link_events (
  id bigint generated by default as identity primary key,
  job_id uuid not null references public.export_jobs (id) on delete cascade,
  kind text not null,
  at timestamptz not null default now(),
  ip_hash text null,                              -- hashed, never the raw IP
  user_agent text null,
  constraint export_link_events_kind_check check (kind in ('email_sent', 'link_opened', 'url_minted', 'expired_hit')),
  constraint export_link_events_ua_len check (user_agent is null or length(user_agent) <= 300)
);
create index if not exists export_link_events_job_at_idx on public.export_link_events (job_id, at desc);

alter table public.export_jobs enable row level security;
alter table public.export_link_events enable row level security;
-- No policies on purpose: only the service role (which bypasses RLS) reads or writes.

revoke all on public.export_jobs from public;
revoke all on public.export_link_events from public;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.export_jobs, public.export_link_events from anon';
    execute 'revoke all on sequence public.export_link_events_id_seq from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on public.export_jobs, public.export_link_events from authenticated';
    execute 'revoke all on sequence public.export_link_events_id_seq from authenticated';
  end if;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant select, insert, update, delete on public.export_jobs, public.export_link_events to service_role';
    execute 'grant usage, select on sequence public.export_link_events_id_seq to service_role';
  end if;
end $$;

-- Private bucket for ZIP parts. bucket limit 50 MB, the Free plan's global upload limit; parts are built at 45 MB, under it. After a Pro upgrade, raise both with a new migration and the constants.
-- No storage.objects policies: downloads only through short signed URLs minted by the server.
do $$ begin
  if exists (select 1 from information_schema.tables where table_schema = 'storage' and table_name = 'buckets') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('company-exports', 'company-exports', false, 52428800, array['application/zip'])
    on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
  end if;
end $$;
